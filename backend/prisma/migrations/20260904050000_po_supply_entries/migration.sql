CREATE TABLE `po_supplies` (
  `id` INTEGER NOT NULL AUTO_INCREMENT,
  `po_number` VARCHAR(100) NOT NULL,
  `po_date` DATE NOT NULL,
  `account_code_id` INTEGER NOT NULL,
  `payee_id` INTEGER NOT NULL,
  `dc_number` VARCHAR(100) NULL,
  `amount` DECIMAL(18,2) NOT NULL,
  `delivery_days` INTEGER NULL,
  `grace_period_days` INTEGER NULL,
  `actual_delivery_date` DATE NULL,
  `manufacturing_date` DATE NULL,
  `expiry_date` DATE NULL,
  `item_type` ENUM('IMPORTED','LOCAL') NOT NULL DEFAULT 'LOCAL',
  `procurement_mode` ENUM('TENDER','QUOTATION') NULL,
  `contingent_invoice_id` INTEGER NULL,
  `created_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  PRIMARY KEY (`id`),
  INDEX `po_supplies_po_number_contingent_invoice_id_idx` (`po_number`,`contingent_invoice_id`),
  CONSTRAINT `po_supplies_account_code_id_fkey` FOREIGN KEY (`account_code_id`) REFERENCES `account_codes`(`id`),
  CONSTRAINT `po_supplies_payee_id_fkey` FOREIGN KEY (`payee_id`) REFERENCES `payees`(`id`),
  CONSTRAINT `po_supplies_contingent_invoice_id_fkey` FOREIGN KEY (`contingent_invoice_id`) REFERENCES `invoices`(`id`) ON DELETE SET NULL
);
